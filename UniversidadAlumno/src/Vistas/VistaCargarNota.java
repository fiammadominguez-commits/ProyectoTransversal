    private void btnCargarNotaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarNotaActionPerformed
        try{
             String seleccionado =(String) cboAlumnos.getSelectedItem();
            if (seleccionado==null ||seleccionado.equalsIgnoreCase("Seleccione Un Alumno")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tiene que seleccionar un Alumno del ComboBox");
                return;
            }
              int filaSeleccionada = tablaMaterias.getSelectedRow();
            if (filaSeleccionada == -1) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tiene que seleccionar una fila");
                return;
            }
            
        float notaNueva= Float.parseFloat(txtNota.getText().trim());
        if (notaNueva<=0 || notaNueva>10) {
            javax.swing.JOptionPane.showMessageDialog(this, "Tiene que colocar una nota valida");
            return;
        }
       
        if (seleccionado != null && !seleccionado.equals("Seleccione Un Alumno")) {
            String[] partes = seleccionado.split("-");
            int idAlumno = Integer.parseInt(partes[0].trim());
            int idMateria = (int) tablaMaterias.getValueAt(filaSeleccionada, 0);
             int anio = (int) tablaMaterias.getValueAt(filaSeleccionada, 2);
             Cursada c = new Cursada(idAlumno, idMateria, anio);
             inscData.cargarNota(c, notaNueva);
               javax.swing.JOptionPane.showMessageDialog(this, "Nota Cargada Correctamente");
               cargarMaterias();
        }
        }
        catch(NumberFormatException ex){
         javax.swing.JOptionPane.showMessageDialog(this, "La nota debe cumplir: no contener caracteres especiales, formularla con punto en lugar de coma"+ ex.getMessage());
        }
        catch(Exception ex){
         javax.swing.JOptionPane.showMessageDialog(this, "Ha ocurrido un error"+ ex.getMessage());
        }
    }//GEN-LAST:event_btnCargarNotaActionPerformed

