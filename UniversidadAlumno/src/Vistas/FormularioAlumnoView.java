    private void bntGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntGuardarActionPerformed
           try {
        int dni = Integer.parseInt(jtDni.getText().trim());
        String nombre = jtNombre.getText().trim();
        
        // Parsear fecha desde el JTextField (AAAA-MM-DD)
        java.sql.Date fecha = java.sql.Date.valueOf(jtFechaNac.getText().trim());
        boolean estado = jcEstado.isSelected();

        // Crear objeto alumno
        Entidades.Alumno alumno = new Entidades.Alumno(dni, nombre, fecha, estado);

        // Crear la conexión e instanciar el DAO
        Persistencia.miConexion conexion = new Persistencia.miConexion("jdbc:mariadb://localhost:3306/universidad", "root", "");
        Persistencia.AlumnoData aluData = new Persistencia.AlumnoData(conexion);

        // Guardar en MariaDB
        aluData.guardarAlumno(alumno);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Alumno guardado exitosamente.");
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El DNI debe ser un número entero válido.");
    } catch (IllegalArgumentException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Usá AAAA-MM-DD (ej: 2002-05-20).");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el alumno: " + e.getMessage());
    }
        
    }//GEN-LAST:event_bntGuardarActionPerformed

